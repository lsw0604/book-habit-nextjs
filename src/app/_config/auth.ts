/**
 * BE가 심는 인증 쿠키 이름. NestJS의 설정과 반드시 같아야 한다.
 *
 * `proxy.ts`는 **둘 중 하나라도 있으면** 세션이 있다고 본다. 하나만 보면
 * 양쪽 모두 실패하는 경우가 있기 때문이다.
 *
 * - access만 보면: 짧게 만료되어 쿠키가 사라진 순간 로그인한 사용자도 튕긴다.
 *   갱신은 인터셉터가 하는데, 리다이렉트가 그 경로에 닿기 전에 끊는다.
 * - refresh만 보면: 화면 요청에 쿠키가 실리지 않아 항상 로그아웃으로 읽힌다.
 *   **이 프로젝트가 실제로 그렇다** — `/library` 문서 요청에는 `access_token`만
 *   실리는 것을 proxy 로그로 확인했다(무한 리다이렉트의 원인이었다).
 *
 * ⚠️ 그래서 지금은 `access_token` 쿠키의 수명에 의존한다. 그 쿠키가 JWT 만료와
 *    같은 `maxAge`로 심겨 있다면, 토큰이 만료되는 순간 쿠키도 사라져 로그인한
 *    사용자가 보호 화면에서 튕긴다. BE에서 **쿠키 수명을 refresh와 같게** 늘리는
 *    것이 정석이다 — 만료 판단은 쿠키가 아니라 서버의 `exp`가 한다.
 *
 * 존재만 확인하고 유효성은 API에 맡긴다. 만료된 값으로 통과해도 화면의 첫 조회가
 * 401을 받고, 인터셉터가 갱신하거나 세션을 끝낸다.
 */
export const ACCESS_TOKEN_COOKIE = "access_token";
export const REFRESH_TOKEN_COOKIE = "refresh_token";
